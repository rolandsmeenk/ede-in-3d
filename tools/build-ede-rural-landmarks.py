#!/usr/bin/env python3
"""Bake the rural landmarks from 3DBAG in the Oude Kerk scene frame."""

import argparse
import gzip
import json
from pathlib import Path
from runpy import run_path

from ede_gis import Frame, SCENE_NAP_ORIGIN

ROOT = Path(__file__).resolve().parents[1]
ESTATES = run_path(str(ROOT / 'tools/build-ede-estate-survey.py'))
SITES = (
    ('harselo-gatehouse', 'Poortgebouw Harselo · De Poort', 'De Kraats', 'Harsloweg',
     (171231, 446132, 171284, 446182), (-3278, 4751), 2.8, (
         ('0228100000017108', 'w271127417', 0x754d3d, 0x564d49),
     )),
    ('ruitenbeekschool', 'Ruitenbeekschool', 'Overwoud', 'Ruitenbeekweg',
     (171879, 459425, 171940, 459489), (-2583.05, -8560.31), 3.0, (
         ('0228100000086547', 'w1328436800', 0x886950, 0x444a4c),
     )),
    ('klein-altena', 'Klein Altena', 'Meulunteren', 'Meulunterseweg',
     (170812, 456810, 170890, 456884), (-3621.8, -5966.6), 3.0, (
         ('0228100000011411', 'w271865663', 0x735343, 0x80705a),
         ('0228100000001748', 'w271864635', 0x6e5141, 0x5e554d),
         ('0228100000037710', 'w271866388', 0x483e35, 0x73634d),
         ('0228100000043191', 'w271866353', 0x725342, 0x59524a),
     )),
    ('walderveense-molen', 'Walderveense Molen', 'Walderveen', 'Renswoudsestraatweg',
     (166367, 458257, 166404, 458288), (-8070.0, -7425.4), 10.0, (
         ('0228100000012429', 'w271597724', 0x714e40, 0x78644d),
     )),
)


def packed(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))


def render(cache, fetch):
    with gzip.open(ROOT / 'assets/ede-map-v1.json.gz') as snapshot:
        frame = Frame(json.load(snapshot)['meta']['lonLatAffine'])
    lines = [
        '// Generated by tools/build-ede-rural-landmarks.py from CC BY 4.0 3DBAG data.',
        'export const RURAL_LANDMARK_SURVEYS = {',
    ]
    sites = []
    for key, name, district, road, bounds, approach, focus, parts in SITES:
        source = ESTATES['load_collection'](cache, key, bounds, fetch)
        mill = key == 'walderveense-molen'
        lines.append(f'  {packed(key)}: [')
        outlines = []
        heights = []
        for bag, osm, wall, roof in parts:
            ground, outline, points, faces = ESTATES['bake'](source, bag, frame, SCENE_NAP_ORIGIN)
            outlines.append(outline)
            heights.append(max(point[1] for point in points) - ground)
            lines.extend([
                '    {',
                f'      bagId: {packed(bag)}, osmId: {packed(osm)},',
                f'      outline: {packed(outline)},',
            ])
            # Photogrammetry includes the sails in the roof surface. Use only the measured ground plan.
            if not mill:
                lines.append(f'      ground: {ground}, wallColor: 0x{wall:06x}, roofColor: 0x{roof:06x},')
                for field, rows in [('points', points), ('faces', faces)]:
                    lines.append(f'      {field}: [')
                    lines.extend('        ' + ', '.join(map(packed, rows[i:i + 5])) + ','
                                 for i in range(0, len(rows), 5))
                    lines.append('      ],')
            lines.append('    },')
        lines.append('  ],')
        outline = outlines[0][0]
        x = round(sum(p[0] for p in outline) / len(outline), 2)
        z = round(sum(p[1] for p in outline) / len(outline), 2)
        ax, az = approach
        sites.append(dict(id=key, name=name, district=district, road=road, x=x, z=z,
                          height=19 if mill else round(max(heights), 2), focusHeight=focus,
                          approach=dict(x=ax, z=az), worldSpace=not mill))
    lines += ['};', '', 'export const EDE_RURAL_LANDMARKS = [']
    lines.extend(f'  {packed(site)},' for site in sites)
    lines += [
        '].map(site => {',
        '  const buildings = RURAL_LANDMARK_SURVEYS[site.id];',
        '  return { ...site, heading: 0, mapScenic: true, osmId: buildings[0].osmId,',
        '    annexOsmIds: buildings.slice(1).map(({ osmId }) => osmId),',
        '    bagIds: buildings.map(({ bagId }) => bagId),',
        '    surveyFootprints: buildings.map(({ outline }) => {',
        '      const [outer, ...holes] = outline.map(ring => ring.map(([x, z]) => ({ x, z })));',
        '      return { outer, holes };',
        '    }),',
        '    colliderHeights: site.worldSpace ? undefined : [site.height],',
        '  };',
        '});', '',
    ]
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path)
    parser.add_argument('--fetch', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    target = ROOT / 'js/ede-rural-landmark-survey.js'
    output = render(args.cache, args.fetch)
    if args.check:
        if target.read_text() != output:
            raise SystemExit(f'{target.name} differs from the survey bake')
    else:
        target.write_text(output)


if __name__ == '__main__':
    main()
