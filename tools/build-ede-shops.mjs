// Builds js/ede-shops.js: named shops, cafés, restaurants, banks and pharmacies from OpenStreetMap
// (© OpenStreetMap contributors, ODbL), projected into the Oude Kerk-centred metre frame of ede-geodata.js.
// usage: node tools/build-ede-shops.mjs [osm_ede.json]
import { readFileSync, writeFileSync } from 'node:fs';
import { EDE_DATA } from '../js/ede-geodata.js';

const { lonLatAffine: A, bounds: [minX, minZ, maxX, maxZ] } = EDE_DATA.meta;
const input = process.argv[2] || new URL('./data/osm_ede.json', import.meta.url);
const data = JSON.parse(readFileSync(input, 'utf8'));
if (!Array.isArray(data.elements) || !data.elements.length || data.remark) throw new Error('Expected a complete Ede OpenStreetMap response');

function shopLocation(el) {
  if (el.type === 'node') return el;
  const points = el.geometry || el.members?.flatMap(member => member.geometry || []);
  if (!points?.length) return el.center || {};
  const lons = points.map(p => p.lon), lats = points.map(p => p.lat);
  return {
    lon: (Math.min(...lons) + Math.max(...lons)) / 2,
    lat: (Math.min(...lats) + Math.max(...lats)) / 2
  };
}

const project = (lon, lat) => {
  const a = lon - A.lon0, b = lat - A.lat0;
  return [A.x[0] + A.x[1] * a + A.x[2] * b, A.z[0] + A.z[1] * a + A.z[2] * b];
};
const amenities = new Set(['cafe', 'restaurant', 'fast_food', 'bank', 'pharmacy']);
const out = [];
for (const el of data.elements) {
  const tags = el.tags || {};
  const kind = tags.shop ? 'shop' : tags.amenity;
  if (!tags.name || (kind !== 'shop' && !amenities.has(kind))) continue;
  const { lon, lat } = shopLocation(el);
  if (!Number.isFinite(lon) || !Number.isFinite(lat)) continue;
  const [x, z] = project(lon, lat);
  if (x < minX || x > maxX || z < minZ || z > maxZ) continue;
  const name = tags.name.trim();
  if (!name) continue;
  if (out.some((o) => o[0] === name && Math.hypot(o[1] - x, o[2] - z) < 4)) continue;
  out.push([name, Math.round(x * 10) / 10, Math.round(z * 10) / 10, kind]);
}
out.sort((a, b) => a[1] - b[1] || a[2] - b[2]);

writeFileSync(new URL('../js/ede-shops.js', import.meta.url),
  '// Generated by tools/build-ede-shops.mjs from OpenStreetMap (© OpenStreetMap contributors, ODbL).\n' +
  '// [name, x, z, kind] in the Oude Kerk-centred metre frame (x east, z south).\n' +
  'export const EDE_SHOPS = [\n' + out.map((o) => '  ' + JSON.stringify(o)).join(',\n') + '\n];\n');
console.log(`${out.length} shops written`);
