import { execFile } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { promisify } from 'node:util';
import { EDE_DATA } from '../js/ede-geodata.js';
import { BICYCLE, FOOT } from '../js/road-access.js';
import { roadAccess } from './ede-road-access.mjs';

const relations = { Ede: 9373249, Kinderroute: 9537406, Lunteren: 9537397, Otterlo: 11532171 };
const roads = new Map(EDE_DATA.roads.map(road => [road.id, road]));
const endpoints = way => [way.nodes[0], way.nodes.at(-1)];
const download = promisify(execFile);

function directedWays(relation, ways) {
  const members = relation.members.filter(({ type }) => type === 'way');
  return members.map(({ ref, role }, i) => {
    const way = ways.get(ref), [start, end] = endpoints(way);
    const previous = endpoints(ways.get(members[(i + members.length - 1) % members.length].ref));
    const next = endpoints(ways.get(members[(i + 1) % members.length].ref));
    const forward = previous.includes(start) && next.includes(end) && role !== 'backward';
    const reverse = previous.includes(end) && next.includes(start) && role !== 'forward';
    if (forward === reverse) return 0;

    const road = roads.get(`w${ref}`);
    if (!road) return 0;
    const direction = forward ? 0 : 1;
    const tags = way.tags;
    // A signed off-road route explicitly supports cycling on otherwise unclassified paths.
    const confirmedPath = /^(path|track)$/.test(tags.highway) &&
      !Object.keys(tags).some(key => /^(bicycle|vehicle|access)(?::forward|:backward)?$/.test(key));
    const access = roadAccess(ref, confirmedPath ? { ...tags, bicycle: 'yes' } : tags).modes;
    const packed = road.modes[0] | road.modes[1];
    const permitted = road.modes[direction] & BICYCLE || confirmedPath && (packed & (BICYCLE | FOOT)) === FOOT;
    return permitted && (access[direction] & BICYCLE) ? (forward ? ref : -ref) : 0;
  });
}

const routes = await Promise.all(Object.entries(relations).map(async ([name, id]) => {
  const { stdout } = await download('curl', ['-fsSL', '--max-time', '25',
    `https://api.openstreetmap.org/api/0.6/relation/${id}/full.json`], { maxBuffer: 8 * 1024 * 1024 });
  const { elements } = JSON.parse(stdout);
  const relation = elements.find(row => row.type === 'relation' && row.id === id);
  if (relation?.tags.route !== 'mtb' || relation.members.some(m => m.type === 'relation')) {
    throw new Error(`Expected a flat MTB route relation for ${id}`);
  }
  const ways = new Map(elements.filter(row => row.type === 'way').map(row => [row.id, row]));
  const signed = directedWays(relation, ways);
  console.log(`${name}: ${signed.filter(Boolean).length}/${signed.length} directed ways`);
  return `  // ${name}, https://www.openstreetmap.org/relation/${id}\n  [${signed.join(',')}],`;
}));

const output = `// Generated by tools/build-ede-mtb-routes.mjs. © OpenStreetMap contributors (ODbL).
// Signed OSM way IDs in riding order. Zero breaks the route at a missing or restricted way.
export const EDE_MTB_ROUTES = [\n${routes.join('\n')}\n];\n`;
await writeFile(new URL('../js/ede-mtb-routes.js', import.meta.url), output);
