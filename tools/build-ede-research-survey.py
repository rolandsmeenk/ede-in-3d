#!/usr/bin/env python3
"""Bake the numbered NIZO and Gelderse Vallei campus shells into the Oude Kerk scene."""
import argparse
import gzip
import json
from pathlib import Path
import struct
from urllib.request import urlopen

from ede_gis import Frame

ROOT = Path(__file__).resolve().parents[1]
CAMPUSES = {
    'NIZO_SURVEY': ('0228100000013349', '0228100000031240', '0228100000033892',
                    '0228100000036731', '0228100000070061'),
    'GELDERSE_VALLEI_SURVEY': ('0228100000006511',),
}
API = 'https://api.3dbag.nl/collections/pand/items/NL.IMBAG.Pand.'


def load(cache, bag_id, fetch):
    path = cache / f'{bag_id}.json'
    if not path.is_file():
        if not fetch:
            raise FileNotFoundError(f'{path} missing. Use --fetch to populate the survey cache.')
        with urlopen(API + bag_id, timeout=45) as response:
            response_bytes = response.read()
        path.write_bytes(response_bytes)
    data = json.loads(path.read_text())
    metadata = data['metadata']
    if not metadata['metadata']['referenceSystem'].endswith('/7415'):
        raise ValueError(f'Unexpected coordinate reference for BAG {bag_id}')
    return data['feature'], metadata['transform']


def survey(feature, transform, frame, datum):
    scale, shift = transform['scale'], transform['translate']
    geometry = next(g for component in feature['CityObjects'].values()
                    for g in component['geometry'] if g['lod'] == '2.2')
    if geometry['type'] != 'Solid':
        raise ValueError(f"Unexpected LoD 2.2 type {geometry['type']}")
    verts, lookup, surfaces = [], {}, []
    for rings, surface_id in zip(geometry['boundaries'][0], geometry['semantics']['values'][0]):
        surface = geometry['semantics']['surfaces'][surface_id]['type']
        if surface not in ('WallSurface', 'RoofSurface'):
            surfaces.append(None)
            continue
        result = [1 if surface == 'RoofSurface' else 0]
        for ring in rings:
            polygon = []
            for index in ring:
                if index not in lookup:
                    e, n, elevation = [p * s + t for p, s, t in zip(feature['vertices'][index], scale, shift)]
                    x, z = frame.rd_to_scene(e, n)
                    lookup[index] = len(verts)
                    verts.append([round(x, 2), round(elevation - datum, 2), round(z, 2)])
                polygon.append(lookup[index])
            result.append(polygon)
        surfaces.append(result)
    return {'id': feature['id'].rsplit('.', 1)[-1], 'vertices': verts, 'surfaces': surfaces}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path, help='Local CityJSONFeature cache')
    parser.add_argument('--fetch', action='store_true')
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    with gzip.open(ROOT / 'assets/ede-map-v1.json.gz') as source:
        frame = Frame(json.load(source)['meta']['lonLatAffine'])
    datum = round(struct.unpack_from('<f', (ROOT / 'assets/ede-ahn.bin').read_bytes(), 24)[0], 2)
    lines = ['// Generated by tools/build-ede-research-survey.py from licensed TU Delft 3D BAG LoD 2.2 data.',
             f'// Scene Y uses the {datum:.2f} m NAP origin in the AHN terrain asset.']
    compact = lambda obj: json.dumps(obj, separators=(',', ':'))
    for name, ids in CAMPUSES.items():
        lines.append(f'export const {name} = [')
        for bag_id in ids:
            data = survey(*load(args.cache, bag_id, args.fetch), frame, datum)
            lines += [f'  {{ id: {compact(data["id"])},', '    vertices: [']
            for i in range(0, len(data['vertices']), 6):
                lines.append('      ' + ','.join(map(compact, data['vertices'][i:i + 6])) + ',')
            lines.append('    ], surfaces: [')
            for i in range(0, len(data['surfaces']), 6):
                lines.append('      ' + ','.join(map(compact, data['surfaces'][i:i + 6])) + ',')
            lines.append('    ] },')
        lines.append('];')
    (ROOT / 'js/ede-research-survey.js').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
