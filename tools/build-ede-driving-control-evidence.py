#!/usr/bin/env python3
"""Extract directional OSM controls and roundabout IDs for the existing Ede map."""
import argparse
from collections import defaultdict
import gzip
import json
from pathlib import Path
from math import hypot

import osmium

ROOT = Path(__file__).resolve().parents[1]


def unit_at(road, x, z, direction):
    points = list(zip(road['pts'][::2], road['pts'][1::2]))
    best = None
    for (ax, az), (bx, bz) in zip(points, points[1:]):
        dx, dz = bx - ax, bz - az
        length = hypot(dx, dz)
        if not length:
            continue
        dx, dz = dx / length, dz / length
        at = min(length, max(0, (x - ax) * dx + (z - az) * dz))
        gap = hypot(x - ax - at * dx, z - az - at * dz)
        if best is None or gap < best[0]:
            best = (gap, round(dx * direction, 4), round(dz * direction, 4))
    return list(best[1:]) if best and best[0] <= 2.5 else None


def extract(source, data):
    roads = {int(road['id'][1:]): road for road in data['roads'] if any(mask & 7 for mask in road['modes'])}
    by_node = defaultdict(list)
    for road in roads.values():
        for node in road['nodeIds']:
            by_node[node].append(road)
    frame = data['meta']['lonLatAffine']
    rings, points = set(), {}

    class Collector(osmium.SimpleHandler):
        def way(self, way):
            if way.id in roads and way.tags.get('junction') == 'roundabout':
                rings.add(roads[way.id]['id'])

        def node(self, node):
            kind = node.tags.get('highway')
            if kind not in ('stop', 'give_way') or node.id not in by_node:
                return
            direction = node.tags.get(f'{kind}:direction') or node.tags.get('direction') or node.tags.get('traffic_sign:direction')
            choices = by_node[node.id]
            if len(choices) != 1:
                return
            road = choices[0]
            if direction not in ('forward', 'backward'):
                if bool(road['modes'][0] & 7) == bool(road['modes'][1] & 7):
                    return
                direction = 'forward' if road['modes'][0] & 7 else 'backward'
            sign = 1 if direction == 'forward' else -1
            if not road['modes'][0 if sign > 0 else 1] & 7:
                return
            delta = (1, node.location.lon - frame['lon0'], node.location.lat - frame['lat0'])
            x, z = (sum(v * coef for v, coef in zip(delta, frame[key])) for key in ('x', 'z'))
            heading = unit_at(road, x, z, sign)
            if heading:
                points[node.id] = [f'n{node.id}', 'stop' if kind == 'stop' else 'yield',
                                   road['id'], road.get('layer', 0), round(x, 2), round(z, 2), *heading]

    for path in source:
        Collector().apply_file(str(path))
    return dict(roundabouts=sorted(rings), lines=[points[key] for key in sorted(points)])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('osm', type=Path, nargs='+', help='Geofabrik OSM PBF snapshots covering the map')
    parser.add_argument('--output', type=Path, default=ROOT / 'js' / 'ede-driving-control-evidence.js')
    args = parser.parse_args()
    with gzip.open(ROOT / 'assets' / 'ede-map-v1.json.gz', 'rt') as f:
        data = json.load(f)
    evidence = extract(args.osm, data)
    encoded = json.dumps(evidence, ensure_ascii=False, separators=(',', ':'))
    args.output.write_text('// Generated by tools/build-ede-driving-control-evidence.py. © OpenStreetMap contributors (ODbL).\n'
                           f'export const EDE_DRIVING_CONTROL_EVIDENCE = {encoded};\n', encoding='utf-8')
    print(f"{len(evidence['roundabouts'])} roundabout ways and {len(evidence['lines'])} directed control nodes")


if __name__ == '__main__':
    main()
