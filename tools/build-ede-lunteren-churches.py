#!/usr/bin/env python3
"""Bake Lunteren church sites from cached 3DBAG CityJSON and the northern map."""

import argparse
import gzip
import importlib.util
import json
from pathlib import Path

from ede_gis import Frame


ROOT = Path(__file__).resolve().parent.parent
SITES = [
    ('bethelkerk-lunteren', 'Bethelkerk Lunteren', '0228100000079981', 509492266, 'De Haverkamp', 10, (-4058.7, -3925.4)),
    ('maranathakerk-lunteren', 'Maranathakerk Lunteren', '0228100000054252', 271717893, 'Hertenlaan', 5, (-3831.72, -4341.55)),
    ('oranjestraat-kerk-lunteren', 'Protestantse Gemeente Lunteren Oranjestraat', '0228100000053639', 271717265, 'Oranjestraat', 7, (-3377.9, -4501.9)),
    ('witte-kerkje-lunteren', 'Het Witte Kerkje', '0228100000055059', 271724140, 'Dokter Kimmijserlaan', 2.7, None),
    ('molukse-kerk-lunteren', 'Molukse Evangelische Kerk Lunteren', '0228100000010672', 271849707, 'Van Limburg Stirumstraat', 3.6, (-3963.68, -4779.8)),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('cache', type=Path, help='3DBAG API responses named by BAG ID')
    parser.add_argument('--out', type=Path, default=ROOT / 'js/ede-lunteren-church-sites.js')
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location('church_bake', ROOT / 'tools/build-ede-other-churches.py')
    bake = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bake)
    with gzip.open(ROOT / 'assets/ede-map-v1.json.gz', 'rt') as source:
        frame = Frame(json.load(source)['meta']['lonLatAffine'])
    with gzip.open(ROOT / 'assets/ede-north-v1.json.gz', 'rt') as source:
        north = json.load(source)
    north_ids = {b['id'] for b in north['buildings']}
    lines = [
        '// Generated by tools/build-ede-lunteren-churches.py. See tools/data/ede-lunteren-churches.md.',
        '// © 3DBAG by tudelft3d and 3DGI, adapted under CC BY 4.0. https://docs.3dbag.nl/en/copyright/',
        'const SHELLS = {',
    ]
    for slug, name, bag, osm, road, focus, pin in SITES:
        shell = bake.bake_shell(args.cache / f'{bag}.json', bag, osm, name, frame, north['bounds'])
        if shell['osm'] not in north_ids:
            raise ValueError(f"Missing northern fallback outline for {name}")
        # These sightlines start on mapped public sidewalks with a clear view of the facade.
        approach = dict(zip(('x', 'z'), pin)) if pin else bake.road_approach(north['roads'], road, shell['center'])
        shell.update(road=road, focusHeight=focus, approach=approach)
        lines.extend((
            f'  {json.dumps(slug)}: {{',
            '    ' + ', '.join(f'{key}: {json.dumps(shell[key], ensure_ascii=False)}' for key in
                               ('name', 'bag', 'osm', 'center', 'base', 'height', 'road', 'focusHeight', 'approach')) + ',',
        ))
        for key in ('points', 'faces'):
            lines.append(f'    {key}: [')
            for start in range(0, len(shell[key]), 5):
                rows = shell[key][start:start + 5]
                lines.append('      ' + ', '.join(json.dumps(row, separators=(',', ':')) for row in rows) + ',')
            lines.append('    ],')
        lines.extend((f"    ground: {json.dumps(shell['ground'], separators=(',', ':'))},", '  },'))
    lines.extend((
        '};',
        '',
        'export const LUNTEREN_CHURCH_SITES = Object.entries(SHELLS).map(([id, churchSurvey]) => {',
        '  const { name, osm, bag, center: [x, z], road, approach, height, focusHeight } = churchSurvey;',
        "  return { id, name, osmId: osm, bagIds: [bag], x, z, road, district: 'Lunteren',",
        '    approach, height, focusHeight, churchSurvey, worldSpace: true, mapScenic: true };',
        '});',
    ))
    args.out.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
