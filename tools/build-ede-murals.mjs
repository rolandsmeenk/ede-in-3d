import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const assets = new URL('../assets/ede-murals/', import.meta.url);
const catalogues = ['centre', 'tunnels', 'flats', 'structures'];

function validPanel(corners) {
  if (corners?.length !== 4 || !corners.every(p => p.length === 3 && p.every(Number.isFinite))) return false;
  const a = corners[1].map((x, axis) => x - corners[0][axis]);
  const b = corners[3].map((x, axis) => x - corners[0][axis]);
  return Math.hypot(a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]) >= 0.005;
}

export async function muralTextureVersion(texture) {
  const contents = await readFile(new URL(texture, assets));
  if (!contents.length) throw new Error(`Empty mural texture ${texture}`);
  return createHash('sha256').update(contents).digest('hex').slice(0, 12);
}

export async function bakeMurals(sites, textureVersion = muralTextureVersion) {
  const seen = new Set();
  const result = [];
  for (const site of sites) {
    const { id, name, artist, referenceDate, sources, surfaces, fallbackBuilding, reach = 230 } = site;
    if (!/^[a-z0-9-]+$/.test(id) || seen.has(id) || !name || !artist || !referenceDate ||
        !sources?.length || !sources.every(url => /^https:\/\//.test(url)) ||
        !Array.isArray(surfaces) || (fallbackBuilding && !/^w[0-9]+$/.test(fallbackBuilding)) || !(reach >= 70 && reach <= 450)) {
      throw new Error(`Invalid mural site ${id}`);
    }
    seen.add(id);
    if (!surfaces.length) continue;
    const bounds = [Infinity, Infinity, Infinity, -Infinity, -Infinity, -Infinity];
    const atlases = new Map();
    for (const { anchor, texture, corners, fallbackCorners, uv = [0, 0, 1, 1] } of surfaces) {
      if (!anchor || !/^[a-z0-9_-]+\/[a-z0-9_-]+\.webp$/.test(texture) ||
          !validPanel(corners) || (fallbackCorners && (!fallbackBuilding || !validPanel(fallbackCorners))) ||
          uv.length !== 4 || !uv.every(value => Number.isFinite(value) && value >= 0 && value <= 1) ||
          uv[0] >= uv[2] || uv[1] >= uv[3]) throw new Error(`Invalid mural surface at ${id} (${anchor})`);
      if (!atlases.has(texture)) {
        const version = await textureVersion(texture);
        atlases.set(texture, { texture, version, p: [], uv: [], f: [] });
      }
      const atlas = atlases.get(texture);
      function append(points, target) {
        for (const point of points) {
          point.forEach((x, axis) => {
            bounds[axis] = Math.min(bounds[axis], x);
            bounds[axis + 3] = Math.max(bounds[axis + 3], x);
            target.push(Math.round(x * 1000) / 1000);
          });
        }
      }
      append(corners, atlas.p);
      if (fallbackBuilding) append(fallbackCorners ?? corners, atlas.f);
      const [u0, v0, u1, v1] = uv;
      atlas.uv.push(u0, v0, u1, v0, u1, v1, u0, v1);
    }
    result.push({ id, bounds, reach, fallbackBuilding, atlases: [...atlases.values()].map(({ f, ...atlas }) =>
      f.length ? { ...atlas, f } : atlas) });
  }
  return { version: 1, sites: result };
}

if (process.argv[1] && new URL(process.argv[1], 'file:').href === import.meta.url) {
  const sites = (await Promise.all(catalogues.map(part =>
    readFile(new URL(`data/ede-murals-${part}.json`, import.meta.url), 'utf8').then(JSON.parse)))).flat();
  const walls = Object.fromEntries(sites.filter(site => site.walls?.length).map(site => [site.id,
    site.walls.map(({ anchor, corners }) => {
      if (!anchor || !validPanel(corners)) throw new Error(`Invalid supporting wall for ${site.id}`);
      return corners.map(point => point.map(value => Math.round(value * 1000) / 1000));
    })]));
  const data = await bakeMurals(sites);
  await writeFile(new URL('placements-v1.json', assets), JSON.stringify(data) + '\n');
  await writeFile(new URL('../js/ede-mural-wall-data.js', import.meta.url),
    '// Generated by tools/build-ede-murals.mjs. The source manifests record surveyed and fitted wall assignments.\n' +
    `export const EDE_MURAL_WALLS = ${JSON.stringify(walls, null, 0)};\n`);
  console.log(`Baked ${data.sites.length} mural sites and ${data.sites.reduce((n, s) => n + s.atlases.length, 0)} paint batches`);
}
