// Refresh road attributes independently of the geometry and graph used by other Ede assets.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { BICYCLE } from '../js/road-access.js';

const LANE_TAG = /^(?:[a-z_]+:)*lanes(?::(?:forward|backward|both_ways))?$/;

function advisoryStrips(road, tags, carriagewayWidth) {
  const strips = [];
  const allowed = road.modes.map(mode => !!(mode & BICYCLE));
  const direction = road.oneway ? road.reverse ? -1 : 1 : 0;
  for (const [side, sign] of [['left', -1], ['right', 1]]) {
    const sideKey = 'cycleway:' + side;
    const facility = tags[sideKey] ?? tags['cycleway:both'] ?? tags.cycleway;
    const detail = key => tags[sideKey + ':' + key] ?? tags['cycleway:both:' + key] ?? tags['cycleway:' + key];
    if (facility !== 'lane' || detail('lane') !== 'advisory' || ['no', 'private'].includes(detail('access'))
      || ['no', 'private'].includes(detail('bicycle'))) continue;
    if (!tags[sideKey] && !tags['cycleway:both'] && direction && direction !== sign) continue;
    const oneWay = detail('oneway');
    const flow = oneWay === 'no' ? 0 : oneWay === '-1' ? -1 : /^(yes|1|true)$/.test(oneWay) ? 1 : direction || sign;
    const laneModes = allowed.map((yes, i) => yes && (!flow || flow === 1 - i * 2));
    if (!laneModes.some(Boolean)) continue;
    const taggedWidth = Number(detail('width'));
    const width = taggedWidth >= 0.6 && taggedWidth <= 3 ? taggedWidth : 1.5;
    strips.push({ offset: sign * (carriagewayWidth - width) / 2, width, allowed: laneModes, kind: 'advisory' });
  }
  return strips;
}

export function buildRoadTags(osm, roads, evidence) {
  if (!Array.isArray(osm.elements) || osm.remark || !osm.elements.length) throw new Error('Incomplete OSM road snapshot');
  const tagsById = new Map(osm.elements.filter(e => e.type === 'way' && e.tags?.highway).map(e => [`w${e.id}`, e.tags]));
  const fields = {};
  let matched = 0;
  for (const road of roads) {
    const tags = tagsById.get(road.id);
    if (tags) matched++;
    const bgtWidth = evidence.ways[road.id]?.width;
    const attributes = bgtWidth > 0 ? { bgtWidth } : {};
    if (tags) {
      const laneTags = Object.fromEntries(Object.entries(tags).filter(([key]) =>
        LANE_TAG.test(key) || key === 'width' || key === 'lane_markings'));
      if (Object.keys(laneTags).length) attributes.laneTags = laneTags;
      if (tags.surface) attributes.surface = tags.surface;
      if (tags.ref) attributes.ref = tags.ref;
      const advisory = advisoryStrips(road, tags, bgtWidth ?? road.bgt?.width ?? road.width);
      if (advisory.length) attributes.cycleAdvisory = advisory;
    }
    if (Object.keys(attributes).length) fields[road.id] = attributes;
  }
  if (matched < roads.length * 0.95) throw new Error(`OSM tags only cover ${matched} of ${roads.length} existing roads`);
  return { fields, matched };
}

export function writeRoadTags(path, fields) {
  writeFileSync(path, '// Generated by tools/build-ede-road-tags.mjs. Road tag data © OpenStreetMap contributors (ODbL).\n'
    + `export const EDE_ROAD_TAGS = ${JSON.stringify(fields)};\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = process.argv[2];
  if (!source) throw new Error('Usage: node tools/build-ede-road-tags.mjs /path/to/osm-road-tags.json');
  const { EDE_DATA } = await import('../js/ede-geodata.js');
  const osm = JSON.parse(readFileSync(source, 'utf8'));
  const evidence = JSON.parse(readFileSync(new URL('./data/ede-bgt-road-evidence.json', import.meta.url), 'utf8'));
  const { fields, matched } = buildRoadTags(osm, EDE_DATA.roads, evidence);
  writeRoadTags(new URL('../js/ede-road-tags.js', import.meta.url), fields);
  console.log(`Refreshed tags for ${matched}/${EDE_DATA.roads.length} existing ways (${Object.keys(fields).length} carry road fields)`);
}
