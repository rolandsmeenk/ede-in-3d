const STONE = 0xa99d84, FRAME = 0x423b33, STEEL = 0x696960;
const WOOD = 0x6d4831, LOUVER = 0x252422;
const GLASS = [0x3f525a, 0x465860, 0x3e5559, 0x4d5f68];
