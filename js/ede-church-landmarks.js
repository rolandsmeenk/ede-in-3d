function frontage([ax, az], [bx, bz]) {
  const width = Math.hypot(bx - ax, bz - az);
  const ux = (bx - ax) / width, uz = (bz - az) / width;
  return { width, ux, uz, nx: uz, nz: -ux, x: (ax + bx) / 2, z: (az + bz) / 2 };
}

function point(wall, u, nap, depth = 0) {
  if (wall.roofClock) depth -= (nap - wall.roofClock[0]) * wall.roofClock[1];
  return [wall.x + wall.ux * u + wall.nx * depth, nap - SCENE_NAP_ORIGIN,
    wall.z + wall.uz * u + wall.nz * depth];
}

function panel(batch, wall, ring, color, depth) {
  batch.polygon([ring.map(([u, nap]) => point(wall, u, nap, depth)).reverse()], color);
}

function rect(batch, wall, u, width, lo, hi, color, depth = 0.045, sheen = 0) {
  if (hi <= lo || width <= 0.001) return;
  const a = point(wall, u - width / 2, lo, depth), b = point(wall, u + width / 2, lo, depth);
  const c = point(wall, u + width / 2, hi, depth), d = point(wall, u - width / 2, hi, depth);
  batch.quad(b, a, d, c, color, sheen);
}

function arch(batch, wall, u, width, lo, hi, color, depth) {
  const radius = width / 2;
  const rise = Math.min(radius, (hi - lo) * 0.6);
  const ring = [[u - radius, lo], [u + radius, lo]];
  for (let i = 0; i <= 12; i++) {
    const angle = i / 12 * Math.PI;
    ring.push([u + radius * Math.cos(angle), hi - rise + rise * Math.sin(angle)]);
  }
  panel(batch, wall, ring, color, depth);
}

function circle(batch, wall, u, center, radius, color, depth) {
  panel(batch, wall, Array.from({ length: 24 }, (_, i) => {
    const angle = i / 12 * Math.PI;
    return [u + Math.cos(angle) * radius, center + Math.sin(angle) * radius];
  }), color, depth);
}

function bar(batch, wall, a, b, width, color, depth) {
  const [x, y] = a, [u, v] = b, len = Math.hypot(u - x, v - y);
  const nx = (v - y) / len * width / 2, ny = -(u - x) / len * width / 2;
  panel(batch, wall, [[x + nx, y + ny], [u + nx, v + ny], [u - nx, v - ny], [x - nx, y - ny]], color, depth);
}

function windowBand(batch, wall, u, width, lo, hi, { columns = 2, rows = 3, tint = GLASS, trim = STEEL, border = FRAME, depth = 0.04 } = {}) {
  rect(batch, wall, u, width + 0.14, lo - 0.06, hi + 0.065, border, depth);
  const cell = width / columns, rise = (hi - lo) / rows;
  for (let i = 0; i < columns; i++) for (let j = 0; j < rows; j++) {
    const left = u - width / 2 + i * cell, right = left + cell;
    const bottom = lo + j * rise, top = bottom + rise;
    const front = depth + 0.025;
    batch.window(point(wall, right, bottom, front), point(wall, left, bottom, front),
      point(wall, left, top, front), point(wall, right, top, front), {
        color: tint[(i + j * 2) % tint.length], frame: border, border: [0.018, 0.018], sheen: 1,
      });
  }
  rect(batch, wall, u, width + 0.24, lo - 0.115, lo - 0.035, trim, depth + 0.08);
}

function door(batch, wall, u, width, lo, hi, { stone = STONE, wood = WOOD, rounded = true } = {}) {
  if (rounded) {
    arch(batch, wall, u, width + 0.36, lo - 0.04, hi + 0.20, stone, 0.027);
    arch(batch, wall, u, width, lo, hi, wood, 0.056);
  } else {
    rect(batch, wall, u, width + 0.22, lo - 0.03, hi + 0.12, stone, 0.027);
    rect(batch, wall, u, width, lo, hi, wood, 0.056);
  }
  rect(batch, wall, u, 0.060, lo, hi - (rounded ? 0.25 : 0.06), FRAME, 0.076);
  for (const offset of [-0.30, -0.18, 0.18, 0.30]) {
    rect(batch, wall, u + width * offset, 0.026, lo + 0.03, hi - (rounded ? 0.42 : 0.08), 0x513828, 0.074);
  }
  rect(batch, wall, u + 0.10, 0.15, lo + 0.94, lo + 0.99, 0xa88658, 0.083);
}

function steps(batch, wall, u, width, threshold, count) {
  const [x, , z] = point(wall, u, threshold, 0.65);
  const ground = terrainHeightAt(x, z);
  const rise = threshold - SCENE_NAP_ORIGIN - ground;
  if (rise < 0.025 || rise > 0.65) return;
  const heading = Math.atan2(-wall.uz, wall.ux);
  for (let i = 1; i <= count; i++) {
    const depth = 0.28 * (count - i + 1);
    const height = rise * i / count + 0.035;
    const [sx, , sz] = point(wall, u, threshold, depth / 2 + 0.02);
    batch.solid(new THREE.BoxGeometry(width - (i - 1) * 0.08, height, depth)
      .rotateY(heading).translate(sx, ground + height / 2 - 0.035, sz), 0x827567);
  }
}

function spindle(batch, x, z, sides, levels, color, phase = Math.PI / 8) {
  const row = (radius, nap) => Array.from({ length: sides }, (_, i) => {
    const angle = phase + (i * 2 * Math.PI) / sides;
    return [x + Math.cos(angle) * radius, nap - SCENE_NAP_ORIGIN, z + Math.sin(angle) * radius];
  });
  const rings = levels.map(([radius, nap]) => row(radius, nap));
  for (let k = 1; k < rings.length; k++) {
    for (let i = 0; i < sides; i++) {
      const j = (i + 1) % sides, a = rings[k - 1], b = rings[k];
      batch.quad(a[j], a[i], b[i], b[j], color);
    }
  }
  batch.polygon([[...rings.at(-1)].reverse()], color);
}

function cross(batch, x, z, nap, height, color) {
  batch.solid(new THREE.BoxGeometry(0.062, height, 0.062).translate(x, nap - SCENE_NAP_ORIGIN + height / 2, z), color);
  batch.solid(new THREE.BoxGeometry(height * 0.57, 0.060, 0.060)
    .translate(x, nap - SCENE_NAP_ORIGIN + height * 0.68, z), color);
}

function frieze(batch, face, normal, nap, color) {
  const y = nap - SCENE_NAP_ORIGIN;
  const hits = [];
  for (let i = 0; i < face.length; i++) {
    const p = face[i], q = face[(i + 1) % face.length];
    if ((p[1] > y) === (q[1] > y)) continue;
    const t = (y - p[1]) / (q[1] - p[1]);
    hits.push([p[0] + (q[0] - p[0]) * t, y, p[2] + (q[2] - p[2]) * t]);
  }
  if (hits.length !== 2) return;
  const { a, b } = wallExtent(hits, normal);
  facePanel(batch, a, b, normal, 0, 1, y - 0.034, y + 0.034, color, 0.024);
}

function church(name, survey, style, details) {
  const batch = new CivicBatch(), masonry = [];
  const ridgePoint = ([x, nap, z]) => style.copperRidge && nap > 39 && Math.hypot(x + 573.0, z - 1045.9) < 3.4;
  const points = survey.points.map(([x, nap, z]) => {
    const height = ridgePoint([x, nap, z]) ? 39.18 : nap;
    const y = Math.min(height, style.shellTop ?? Infinity) - SCENE_NAP_ORIGIN;
    return [x, Math.abs(nap - survey.base) <= 0.035 ? Math.min(y, terrainHeightAt(x, z) - 0.06) : y, z];
  });
  const trim = [];
  for (const [i, [roof, ...rings]] of survey.faces.entries()) {
    const faces = rings.map(ring => ring.map(i => points[i]));
    const face = faces[0];
    const ridge = rings[0].some(i => ridgePoint(survey.points[i]));
    const start = batch.vertices.length / 3;
    batch.polygon(faces, ridge ? 0x416861 : roof ? (style.roofTints?.[i] ?? style.roof) : style.wall);
    if (roof || ridge || style.masonry === false) continue;
    const normal = polygonNormal(face);
    for (let i = start; i < batch.vertices.length / 3; i++) masonry[i] = 1;
    if (style.friezes && Math.abs(normal.y) < 0.2) trim.push([face, normal]);
  }
  for (const [face, normal] of trim) {
    for (const nap of style.friezes) frieze(batch, face, normal, nap, style.band);
  }
  details(batch, masonry);

  const outer = survey.ground[0].map(i => ({ x: points[i][0], z: points[i][2] }));
  const holes = survey.ground.slice(1).map(ring => ring.map(i => ({ x: points[i][0], z: points[i][2] })));
  const colliders = [{
    minX: Math.min(...outer.map(p => p.x)), maxX: Math.max(...outer.map(p => p.x)),
    minZ: Math.min(...outer.map(p => p.z)), maxZ: Math.max(...outer.map(p => p.z)),
    minY: Math.min(survey.base - SCENE_NAP_ORIGIN, ...outer.map(p => terrainHeightAt(p.x, p.z) - 0.06)),
    maxY: Math.max(...points.map(p => p[1])), polygon: { outer, holes },
  }];
  const group = makeGroup(name, batch, colliders);
  const mesh = group.children[0], coordinates = [];
  const { position, normal } = mesh.geometry.attributes;
  for (let i = 0; i < position.count; i++) {
    coordinates.push((position.getX(i) * normal.getZ(i) - position.getZ(i) * normal.getX(i)) / 1.08,
      position.getY(i) / 0.64);
  }
  mesh.geometry.setAttribute('uv', new THREE.Float32BufferAttribute(coordinates, 2));
  mesh.geometry.setAttribute('churchMasonry', new THREE.Float32BufferAttribute(
    Float32Array.from({ length: position.count }, (_, i) => masonry[i] ?? 0), 1));
  masonryTexture ??= createFacadeSurfaceTexture().texture;
  const tint = mesh.material.colorNode;
  const masonryTint = mix(1, texture(masonryTexture, uv()).r.mul(0.83).add(0.31),
    attribute('churchMasonry', 'float'));
  // Window coverage materials supply their own vertex tint instead of using the automatic tint.
  mesh.material.colorNode = (tint ? tint.mul(tint) : vertexColor()).mul(masonryTint);
  return group;
}

