export function polygonNormal(points) {
  const normal = new THREE.Vector3();
  for (let i = 0; i < points.length; i++) {
    const [ax, ay, az] = points[i], [bx, by, bz] = points[(i + 1) % points.length];
    normal.x += (ay - by) * (az + bz);
    normal.y += (az - bz) * (ax + bx);
    normal.z += (ax - bx) * (ay + by);
  }
  return normal.normalize();
}

export class CivicBatch {
  geometry = new THREE.BufferGeometry();
  vertices = [];
  colors = [];
  glossy = [];
  tint = new THREE.Color();

  triangle(a, b, c, color, sheen = 0) {
    this.vertices.push(...a, ...b, ...c);
    this.tint.set(color);
    const { r, g, b: blue } = this.tint;
    this.colors.push(r, g, blue, r, g, blue, r, g, blue);
    this.glossy.push(sheen, sheen, sheen);
  }

  quad(a, b, c, d, color, sheen = 0) {
    this.triangle(a, b, c, color, sheen);
    this.triangle(a, c, d, color, sheen);
  }

  polygon(rings, color) {
    const normal = polygonNormal(rings[0]);
    if (normal.lengthSq() === 0) return;
    const x = Math.abs(normal.x), y = Math.abs(normal.y), z = Math.abs(normal.z);
    const axis = x > y && x > z ? 0 : y > z ? 1 : 2;
    const projected = rings.map(ring => ring.map(p => new THREE.Vector2(p[(axis + 1) % 3], p[(axis + 2) % 3])));
    const points = rings.flat();
    for (const [i, j, k] of THREE.ShapeUtils.triangulateShape(projected[0], projected.slice(1))) {
      const a = points[i], b = points[j], c = points[k];
      const orientation = polygonNormal([a, b, c]).dot(normal);
      if (orientation > 0) this.triangle(a, b, c, color);
      else if (orientation < 0) this.triangle(a, c, b, color);
    }
  }

  solid(geometry, color) {
    const position = geometry.getAttribute('position'), index = geometry.index;
    const points = Array.from({ length: position.count }, (_, i) => [position.getX(i), position.getY(i), position.getZ(i)]);
    for (let i = 0; i < (index?.count ?? position.count); i += 3) {
      const j = index ? [index.getX(i), index.getX(i + 1), index.getX(i + 2)] : [i, i + 1, i + 2];
      this.triangle(points[j[0]], points[j[1]], points[j[2]], color);
    }
    geometry.dispose();
  }

  mesh({ passage = false } = {}) {
    const geometry = this.geometry;
    geometry.setAttribute('position', new THREE.Float32BufferAttribute(this.vertices, 3));
    geometry.setAttribute('color', new THREE.Float32BufferAttribute(this.colors, 3));
    geometry.setAttribute('civicGloss', new THREE.Float32BufferAttribute(this.glossy, 1));
    geometry.computeVertexNormals();
    geometry.computeBoundingBox();
    if (passage) carveBagBuildingPassages(geometry, { removeLandmarks: false });
    const material = new THREE.MeshStandardNodeMaterial({ vertexColors: true });
    material.roughnessNode = mix(0.86, 0.26, attribute('civicGloss', 'float'));
    const mesh = new THREE.Mesh(geometry, material);
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    return mesh;
  }
}

export function along(a, b, t) {
  return { x: a.x + (b.x - a.x) * t, z: a.z + (b.z - a.z) * t };
}

function edgeQuad(batch, a, b, lo, hi, color, sheen = 0) {
  if (hi <= lo) return;
  batch.quad([a.x, lo, a.z], [b.x, lo, b.z], [b.x, hi, b.z], [a.x, hi, a.z], color, sheen);
}

export function offsetEdge(a, b, normal, offset) {
  return [a, b].map(p => ({ x: p.x + normal.x * offset, z: p.z + normal.z * offset }));
}

export function facePanel(batch, a, b, n, u, v, lo, hi, color, offset = 0.02, sheen = 0) {
  const [p, q] = offsetEdge(along(a, b, u), along(a, b, v), n, offset);
  if (-(q.z - p.z) * n.x + (q.x - p.x) * n.z < 0) edgeQuad(batch, q, p, lo, hi, color, sheen);
  else edgeQuad(batch, p, q, lo, hi, color, sheen);
}

export function wallExtent(points, normal) {
  const dx = normal.z, dz = -normal.x;
  let a, b, lo, hi;
  for (const [x, , z] of points) {
    const t = x * dx + z * dz;
    if (lo === undefined || t < lo) { lo = t; a = { x, z }; }
    if (hi === undefined || t > hi) { hi = t; b = { x, z }; }
  }
  return { a, b, width: hi - lo };
}

export function wallColliders(a, b, low, high, thickness = 0.30) {
  if (high <= low) return [];
  const dx = b.x - a.x, dz = b.z - a.z, width = Math.hypot(dx, dz);
  if (width < 0.08) return [];
  const openings = buildingPassageOpenings(a, b);
  const breaks = [...new Set([0, 1, ...openings.flatMap(({ from, to }) => [Math.max(0, from), Math.min(1, to)])])].sort((x, y) => x - y);
  const result = [];
  for (let i = 1; i < breaks.length; i++) {
    const from = breaks[i - 1], to = breaks[i], middle = (from + to) / 2;
    const hx = width * (to - from) / 2, hz = thickness / 2;
    if (hx < 0.04) continue;
    const { x: cx, z: cz } = along(a, b, middle);
    const cs = dx / width, sn = -dz / width;
    const ex = Math.abs(cs) * hx + Math.abs(sn) * hz, ez = Math.abs(sn) * hx + Math.abs(cs) * hz;
    const active = openings.filter(({ from, to }) => middle >= from && middle <= to);
    const lowY = Math.max(low, ...active.map(cut => {
      const p = along(a, b, from), q = along(a, b, to);
      return Math.max(cut.roofAt(p.x, p.z), cut.roofAt(q.x, q.z));
    }));
    if (lowY >= high) continue;
    result.push({ minX: cx - ex, maxX: cx + ex, minZ: cz - ez, maxZ: cz + ez,
      minY: lowY, maxY: high, kind: active.length ? 'passage-lintel' : undefined, obb: { cx, cz, hx, hz, cs, sn } });
  }
  return result;
}

export function makeGroup(name, batch, colliders, passage = false) {
  const group = new THREE.Group();
  group.name = name;
  group.add(batch.mesh({ passage }));
  group.userData.colliders = colliders;
  return group;
}

function raadhuisFront(batch, a, b, normal, width, low, roof) {
  const midX = (a.x + b.x) / 2;
  const middle = along(a, b, 0.5);
  const grade = terrainHeightAt(middle.x, middle.z);
  const bays = Math.max(2, Math.round(width / 2.70));
  const windows = Math.round((roof - Math.max(low, grade)) / 3.40);
  const westGlazedHall = midX < 106 && normal.z > 0.5;
  const curvedCouncilRoom = midX > 226 && midX < 246 && middle.z > 46 && normal.z > 0.10;
  const colors = [0x56737a, 0x607982, 0x4e656c, 0x6d8790, 0x445c67];
  for (let level = 0; level < windows; level++) {
    if (westGlazedHall && level > 0) break;
    const y = roof - 0.85 - level * 3.20;
    const councilWindow = curvedCouncilRoom && level === 1;
    const bottom = Math.max(low + 0.25, y - (councilWindow ? 2.15 : 1.22));
    if (bottom < grade + 0.35) break;
    // The later council-room window interrupts the upper concrete band on the curved end.
    if (councilWindow)
      facePanel(batch, a, b, normal, 0, 1, bottom - 0.20, y + 0.23, 0xb5bab8, 0.18);
    facePanel(batch, a, b, normal, 0.01, 0.99, bottom, y, 0x242c2d, councilWindow ? 0.19 : 0.025);
    for (let i = 0; i < bays; i++) {
      facePanel(batch, a, b, normal, (i + 0.035) / bays, (i + 0.965) / bays,
        bottom + 0.065, y - 0.065, colors[(i + level * 2) % colors.length],
        councilWindow ? 0.205 : 0.04, 1);
      if (i > 0 && i % 3 === 0 && level + 1 < windows && y - 3.12 > grade + 0.2)
        facePanel(batch, a, b, normal, i / bays - 0.12 / width, i / bays + 0.12 / width,
          y - 3.12, bottom - 0.04, orange);
    }
    facePanel(batch, a, b, normal, 0, 1, y + 0.06, y + 0.14, 0x837a6c, 0.015);
  }
  if (westGlazedHall) {
    const top = roof - 3.05, bottom = Math.max(low + 0.15, grade + 0.45);
    facePanel(batch, a, b, normal, 0.015, 0.985, bottom, top, 0x2b3838);
    for (let i = 0; i < bays; i++) facePanel(batch, a, b, normal, (i + 0.04) / bays, (i + 0.94) / bays,
      bottom + 0.15, top - 0.11, i % 4 === 0 ? 0x526e73 : 0x405a5c, 0.044, 1);
  }
}

