const red = 0x9f2728, deepRed = 0x802328, metal = 0x8e9493, brick = 0x755c51;
const glass = [0x4e646c, 0x536972, 0x647b84, 0x4a5d63];

function glazing(batch, a, b, normal, width, lo, hi, gap = 1.7) {
  if (hi - lo < 0.65) return;
  const bays = Math.max(1, Math.round(width / gap));
  const rows = Math.max(1, Math.round((hi - lo) / 1.4));
  facePanel(batch, a, b, normal, 0.02, 0.98, lo - 0.05, hi + 0.06, 0x383e41);
  for (let i = 0; i < bays; i++) for (let j = 0; j < rows; j++) {
    const x0 = 0.026 + 0.95 * i / bays, x1 = 0.026 + 0.95 * (i + 1) / bays;
    const y0 = lo + (hi - lo) * j / rows, y1 = lo + (hi - lo) * (j + 1) / rows;
    facePanel(batch, a, b, normal, x0 + 0.035 / width, x1 - 0.035 / width,
      y0 + 0.035, y1 - 0.035, glass[(i * 3 + j) % glass.length], 0.037, 1);
  }
}

function shell(batch, colliders, [points, faces], cinema) {
  const roofRgb = [];
  const roofTint = sampleRoofColor(cinema ? 'w56105004' : 'w271376070', roofRgb)
    ? new THREE.Color().setRGB(...roofRgb) : cinema ? 0x727573 : 0x898879;
  for (const [roof, ...ids] of faces) {
    const rings = ids.map(ring => ring.map(i => points[i]));
    const outer = rings[0];
    const normal = polygonNormal(outer);
    if (normal.lengthSq() === 0) continue;
    const center = outer.reduce((v, p) => [v[0] + p[0] / outer.length, v[1] + p[2] / outer.length], [0, 0]);
    const terrain = terrainHeightAt(...center);
    if (roof) {
      batch.polygon(rings, roof === 2 ? 0x727c56 : roofTint);
      continue;
    }
    const { a, b, width } = wallExtent(outer, normal);
    const lo = Math.min(...outer.map(p => p[1]));
    const hi = Math.max(...outer.map(p => p[1]));
    const streetSide = normal.z < -0.20;
    const box = cinema && hi > 0.1;
    const color = cinema ? box ? (streetSide ? red : deepRed) : 0x62615c
      : Math.abs(normal.x) > 0.65 ? brick : 0x9e9d89;
    batch.polygon(rings, color);
    if (width < 1.8 || hi - lo < 1.1) continue;
    colliders.push(...wallColliders(a, b, Math.max(lo, terrain - 0.55), hi));
    if (cinema && box && width > 3.5) {
      for (let y = Math.max(lo + 0.8, terrain + (streetSide ? 4.4 : 0.4)); y < hi - 0.22; y += 0.56)
        facePanel(batch, a, b, normal, 0.016, 0.984, y, y + 0.025, 0x752025, 0.012);
      if (streetSide) {
        const sill = Math.max(lo, terrain) + 0.45;
        glazing(batch, a, b, normal, width, sill, Math.min(sill + 2.3, hi - 0.4));
      }
    }
    if (!cinema && Math.abs(normal.x) > 0.55 && width > 4.8) {
      const sill = Math.max(lo, terrain) + 0.6;
      glazing(batch, a, b, normal, width, sill, Math.min(sill + 2.7, hi - 0.55), 1.65);
      const lintel = Math.min(sill + 2.85, hi - 0.48);
      facePanel(batch, a, b, normal, 0.01, 0.99, lintel, lintel + 0.42, metal, 0.065);
    }
  }
}

function horizontalOverhang(batch, corners, heights, color, depth = 0.35) {
  const up = corners.map(([x, z], i) => [x, heights[i], z]);
  const down = up.map(([x, y, z]) => [x, y - depth, z]);
  batch.polygon([up], color);
  batch.polygon([[...down].reverse()], 0x6f7169);
  for (let i = 0; i < corners.length; i++) {
    const j = (i + 1) % corners.length;
    batch.quad(up[j], up[i], down[i], down[j], metal);
  }
}

function addSign(group, config) {
  const sign = civicSigns([config]);
  if (sign) group.add(sign);
}

