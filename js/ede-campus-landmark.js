function bridge(batch, colliders) {
  const northWest = { x: -511.98, z: 2906.21 }, northEast = { x: -481.93, z: 2905.46 };
  const southWest = { x: -511.24, z: 2910.74 }, southEast = { x: -481.05, z: 2909.91 };
  const ring = [northWest, southWest, southEast, northEast];
  const bottom = CHE_BRIDGE_SOFFIT, top = CHE_BRIDGE_ROOF;
  batch.quad(...ring.map(p => point(p, top)), roofSilver);
  batch.quad(...[...ring].reverse().map(p => point(p, bottom)), 0x888780);
  const glass = [];
  for (const [a, b] of [[northEast, northWest], [southWest, southEast]]) {
    const width = Math.hypot(b.x - a.x, b.z - a.z);
    const n = new THREE.Vector3(-(b.z - a.z), 0, b.x - a.x).normalize();
    const face = { a, b, n, width };
    panel(batch, face, 0, 1, bottom, bottom + 0.36, roofSilver, 0.015);
    panel(batch, face, 0, 1, top - 0.25, top, roofSilver, 0.015);
    mosaic(batch, face, bottom + 0.40, top - 0.29, 0.021);
    for (let i = 0; i < 13; i++) {
      const t = i / 12;
      panel(batch, face, Math.max(0, t - 0.002), Math.min(1, t + 0.002), bottom + 0.32, top - 0.22, steel, 0.037);
    }
    const [p, q] = offsetEdge(a, b, n, 0.009);
    const lo = bottom + 0.32, hi = top - 0.22;
    glass.push(...point(p, lo), ...point(q, lo), ...point(q, hi), ...point(p, lo), ...point(q, hi), ...point(p, hi));
  }
  for (const [a, b] of [[northWest, southWest], [southEast, northEast]]) {
    batch.quad(point(a, bottom), point(b, bottom), point(b, top), point(a, top), steel);
  }
  colliders.push({
    minX: northWest.x, maxX: southEast.x, minZ: northEast.z, maxZ: southWest.z, minY: bottom, maxY: top,
    polygon: { outer: ring, holes: [] }, kind: 'passage-roof',
  });
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(glass, 3));
  geometry.computeVertexNormals();
  const material = new THREE.MeshStandardMaterial({
    color: 0x526c75, roughness: 0.34, side: THREE.DoubleSide, transparent: true, opacity: 0.68, depthWrite: false,
  });
  return new THREE.Mesh(geometry, material);
}

function wideStair(batch) {
  const left = { x: -303.31, z: 3200.68 }, right = { x: -295.43, z: 3199.18 };
  const topLeft = { x: -306.21, z: 3185.75 }, topRight = { x: -298.87, z: 3184.57 };
  const base = terrainHeightAt(-299, 3198.6) - 0.02, top = -2.02;
  const count = 16;
  for (let i = 0; i < count; i++) {
    const a = along(left, topLeft, i / count), b = along(right, topRight, i / count);
    const c = along(left, topLeft, (i + 1) / count), d = along(right, topRight, (i + 1) / count);
    const y = THREE.MathUtils.lerp(base, top, (i + 1) / count);
    const below = THREE.MathUtils.lerp(base, top, i / count);
    batch.quad(point(a, y), point(b, y), point(d, y), point(c, y), 0xabaaa1);
    batch.quad(point(a, below), point(b, below), point(b, y), point(a, y), 0x85867d);
  }
  // Rails and the approach stair are exterior detail. The level public entrance is beside the stair.
  const rails = [[left, topLeft], [right, topRight]];
  for (const [a, b] of rails) {
    batch.quad(point(a, base + 0.95), point(b, top + 0.95), point(b, top + 1.01), point(a, base + 1.01), steel);
    batch.quad(point(b, top + 0.95), point(a, base + 0.95), point(a, base + 1.01), point(b, top + 1.01), steel);
    for (let i = 0; i < 6; i++) {
      const p = along(a, b, i / 5), y = THREE.MathUtils.lerp(base, top, i / 5) + 0.48;
      batch.solid(new THREE.BoxGeometry(0.055, 0.97, 0.055).translate(p.x, y, p.z), steel);
    }
  }
}

function knaap(batch, colliders, labels) {
  shell(batch, colliders, HALL, {
    roofId: 'w562784777', ground: -6.06, roofColor: 0xa4a49c,
    wallColor: (face, id) => face && face.hi < -1.8 ? 0x4b4a44 : copper[id % copper.length],
    detail(face, id) {
      const { lo, hi, width, n } = face;
      if (width < 1.7 || hi - lo < 1.3) return;
      const east = n.x > 0.72, south = n.z > 0.72;
      if (hi > 1.32) {
        for (let y = Math.max(-2.18, lo + 0.5); y < hi - 0.16; y += 1.22)
          panel(batch, face, 0.009, 0.991, y, y + 0.013, 0x7e543e, 0.011);
      }
      if (east && width > 4.0) {
        curtainWall(batch, face, 0, 1, Math.max(lo + 0.20, -5.37), Math.min(-2.06, hi - 0.24), 1.51);
        curtainWall(batch, face, 0, 1, Math.max(lo + 0.21, -0.75), Math.min(1.85, hi - 0.26), 1.51);
        if (id === 29) {
          curtainWall(batch, face, 0.0, 0.39, 2.98, 4.8, 1.5);
          labels.push(label(face, 0.41, 0.89, 3.18, 4.7, 'Van der Knaaphal'));
        }
        if (id === 62) {
          const door = [-4.51, -2.15];
          panel(batch, face, 0.075, 0.19, ...door, 0x3e494b, 0.068, 1);
          for (const u of [0.075, 0.135, 0.19]) panel(batch, face, u, u + 0.008, ...door, steel, 0.075);
        }
      } else if (south && width > 6) {
        curtainWall(batch, face, 0.03, 0.97, Math.max(lo + 0.25, -0.75), Math.min(0.20, hi - 0.3), 1.8);
      }
    },
  });
  const heightAt = localRoofHeight(HALL);
  roofPanels(batch, heightAt, [[-361.6, 3158], [-316.5, 3149.8], [-310.52, 3183.6], [-354.8, 3192.2]], 18, 16, 0.0018);
  roofPanels(batch, heightAt, [[-314.2, 3137.9], [-311.7, 3137.45], [-305.5, 3172.4], [-308.15, 3172.87]], 2, 17, 0.014);
  wideStair(batch);
}

export function createCheCampus() {
  const group = new THREE.Group();
  const offices = new CivicBatch(), hall = new CivicBatch(), colliders = [], labels = [];
  spectrum(offices, colliders, labels);
  prisma(offices, colliders, labels);
  const signY = terrainHeightAt(-457, 2970);
  offices.solid(new THREE.BoxGeometry(8.0, 0.32, 0.72).rotateY(0.195).translate(-457, signY + 0.13, 2970), plinth);
  labels.push(label({
    a: { x: -460.9, z: 2970.75 }, b: { x: -453.1, z: 2969.23 }, n: { x: 0.194, z: 0.981 },
  }, 0, 1, signY + 0.12, signY + 3.12, 'CHE'));
  const bridgeGlass = bridge(offices, colliders);
  knaap(hall, colliders, labels);
  group.add(makeGroup('CHE Spectrum, Prisma and footbridge', offices, colliders), bridgeGlass,
    makeGroup('Van der Knaaphal', hall, []));
  group.userData.colliders = colliders;
  const signs = campusSigns(labels);
  if (signs) group.add(signs);
  return group;
}
