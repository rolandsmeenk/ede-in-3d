function campusSigns(labels) {
  if (typeof document === 'undefined') return null;
  const canvas = document.createElement('canvas');
  const row = 64;
  canvas.width = 1024;
  canvas.height = 2 ** Math.ceil(Math.log2(labels.length * row));
  const ctx = canvas.getContext('2d');
  const positions = [], uvs = [];
  ctx.font = 'bold 54px sans-serif';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  for (const [i, { a, b, lo, hi, text, textColor }] of labels.entries()) {
    const y = i * row;
    ctx.save();
    ctx.translate(canvas.width / 2, y + row / 2);
    ctx.scale(0.85 * canvas.width / ctx.measureText(text).width, 1);
    ctx.fillStyle = textColor;
    ctx.fillText(text, 0, 0);
    ctx.restore();
    positions.push(...point(a, lo), ...point(b, lo), ...point(b, hi), ...point(a, lo), ...point(b, hi), ...point(a, hi));
    const v = 1 - (y + row - 1) / canvas.height, w = 1 - (y + 1) / canvas.height;
    uvs.push(0, v, 1, v, 1, w, 0, v, 1, w, 0, w);
  }
  const map = new THREE.CanvasTexture(canvas);
  map.colorSpace = THREE.SRGBColorSpace;
  map.anisotropy = 8;
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));
  geometry.setAttribute('uv', new THREE.Float32BufferAttribute(uvs, 2));
  geometry.computeVertexNormals();
  return new THREE.Mesh(geometry, new THREE.MeshStandardMaterial({ map, alphaTest: 0.39, roughness: 0.86 }));
}

function wallFace(vertices) {
  const normal = polygonNormal(vertices);
  if (Math.abs(normal.y) > 0.2) return null;
  const face = wallExtent(vertices, normal);
  if (face.width < 0.065) return null;
  const levels = vertices.map(v => v[1]);
  return { ...face, n: normal, lo: Math.min(...levels), hi: Math.max(...levels) };
}

function groundWall(batch, colliders, face, base, color) {
  const { a, b, width, lo, hi } = face;
  const count = Math.max(1, Math.ceil(width / 5));
  let minY = lo;
  if (lo <= base + 0.10) {
    for (let i = 0; i < count; i++) {
      const p = along(a, b, i / count), q = along(a, b, (i + 1) / count);
      const y0 = Math.min(lo, terrainHeightAt(p.x, p.z) - 0.12);
      const y1 = Math.min(lo, terrainHeightAt(q.x, q.z) - 0.12);
      if (Math.min(y0, y1) < lo - 0.001) batch.quad(point(p, y0), point(q, y1), point(q, lo), point(p, lo), color);
      minY = Math.min(minY, y0, y1);
    }
  }
  if (hi - minY > 0.35) colliders.push(...wallColliders(a, b, minY, hi));
}

function shell(batch, colliders, [points, surfaces], { roofId, ground, roofColor, wallColor, detail }) {
  const rgb = [];
  const roof = sampleRoofColor(roofId, rgb) ? new THREE.Color().setRGB(...rgb) : roofColor;
  for (const [isRoof, id, ...rings] of surfaces) {
    const vertices = rings.map(ring => ring.map(j => points[j]));
    if (isRoof) {
      batch.polygon(vertices, roof);
      continue;
    }
    const face = wallFace(vertices[0]);
    const color = face ? wallColor(face, id) : wallColor(null, id);
    batch.polygon(vertices, color);
    if (!face) continue;
    groundWall(batch, colliders, face, ground, color);
    detail(face, id);
  }
}

function localRoofHeight([points, surfaces]) {
  const triangles = [];
  for (const [roof, , ...rings] of surfaces) {
    if (!roof) continue;
    const projected = rings.map(ring => ring.map(index => new THREE.Vector2(points[index][0], points[index][2])));
    const vertices = rings.flat().map(index => points[index]);
    for (const [i, j, k] of THREE.ShapeUtils.triangulateShape(projected[0], projected.slice(1))) {
      const [a, b, c] = [vertices[i], vertices[j], vertices[k]];
      const det = (b[0] - a[0]) * (c[2] - a[2]) - (c[0] - a[0]) * (b[2] - a[2]);
      if (Math.abs(det) > 0.0001) triangles.push({ a, b, c, det });
    }
  }
  return (x, z) => {
    let y = -Infinity;
    for (const { a, b, c, det } of triangles) {
      const dx = x - a[0], dz = z - a[2];
      const u = (dx * (c[2] - a[2]) - dz * (c[0] - a[0])) / det;
      const v = ((b[0] - a[0]) * dz - (b[2] - a[2]) * dx) / det;
      if (u >= 0 && v >= 0 && u + v <= 1) y = Math.max(y, a[1] + u * (b[1] - a[1]) + v * (c[1] - a[1]));
    }
    return y;
  };
}

function roofPanels(batch, heightAt, corners, columns, rows, margin = 0.01) {
  const p = (s, t) => {
    const [x, z] = corners[0].map((a, i) => THREE.MathUtils.lerp(
      THREE.MathUtils.lerp(a, corners[1][i], s), THREE.MathUtils.lerp(corners[3][i], corners[2][i], s), t));
    return [x, heightAt(x, z) + 0.10, z];
  };
  for (let j = 0; j < rows; j++) for (let i = 0; i < columns; i++) {
    const s = i / columns + margin, t = j / rows + margin * 0.5;
    const u = (i + 1) / columns - margin, v = (j + 1) / rows - margin * 0.5;
    const panel = [p(s, t), p(s, v), p(u, v), p(u, t)];
    const heights = panel.map(point => point[1]);
    if (heights.every(Number.isFinite) && Math.max(...heights) - Math.min(...heights) < 0.26) {
      batch.quad(...panel, i % 3 === 1 ? 0x354a59 : 0x3c4f5e, 0.34);
    }
  }
}

