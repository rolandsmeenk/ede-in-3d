const DOOR = { x: -1.55, z: 1.02, base: 0.08, width: 2.48, height: 3.5, rise: 0.97 };

let sharedMaterial;
function facadeMaterial() {
  if (!sharedMaterial) {
    const material = new THREE.MeshStandardNodeMaterial({ metalness: 0.02 });
    const finish = attribute('frisoFinish', 'vec2');
    const grain = texture(createFacadeSurfaceTexture().texture, uv());
    const masonry = mix(grain.r, grain.b, step(1.5, finish.x));
    material.colorNode = vertexColor().mul(mix(1, masonry.mul(0.54).add(0.52), step(0.5, finish.x)));
    material.roughnessNode = finish.y;
    sharedMaterial = material;
  }
  return sharedMaterial;
}

function openingOutline(width, height, rise) {
  const edge = [[-width / 2, 0], [width / 2, 0]];
  if (!rise) return edge.concat([[width / 2, height], [-width / 2, height]]);
  for (let i = 0; i <= 10; i++) {
    const angle = Math.PI * i / 10;
    edge.push([Math.cos(angle) * width / 2, height - rise + Math.sin(angle) * rise]);
  }
  return edge;
}

function surveyGeometry() {
  const pos = [], normals = [], color = [], coords = [], finish = [];
  const points = SURVEY_POINTS.map(p => new THREE.Vector3(...p));
  const brick = new THREE.Color(BRICK), tile = new THREE.Color(TILE), flatRoof = new THREE.Color(0x615b55);
  const aerial = [0, 0, 0];
  if (sampleRoofColor('w271576736', aerial)) tile.lerp(new THREE.Color().setRGB(...aerial), 0.34);
  const axis = new THREE.Vector3(0, 1, 0), roofAxis = new THREE.Vector3(0, 0, 1);
  for (const [kind, outer, ...holes] of SURVEY_FACES) {
    const rings = [outer, ...holes].map(ring => ring.map(i => points[i]));
    const normal = new THREE.Vector3();
    const a = rings[0][0];
    for (let i = 1; i < outer.length - 1; i++) {
      normal.add(new THREE.Vector3().subVectors(rings[0][i], a)
        .cross(new THREE.Vector3().subVectors(rings[0][i + 1], a)));
    }
    if (normal.lengthSq() < 1e-9) continue;
    normal.normalize();
    const horizontalRoof = kind === 1 && normal.y > 0.985;
    const u = new THREE.Vector3().crossVectors(Math.abs(normal.y) < 0.98 ? axis : roofAxis, normal).normalize();
    const v = new THREE.Vector3().crossVectors(normal, u);
    const frontDoor = kind === 0 && normal.z > 0.99 &&
      outer.every(i => Math.abs(points[i].z - DOOR.z) < 0.015) &&
      Math.min(...rings[0].map(p => p.x)) < DOOR.x - DOOR.width / 2 &&
      Math.max(...rings[0].map(p => p.x)) > DOOR.x + DOOR.width / 2 &&
      Math.min(...rings[0].map(p => p.y)) < DOOR.base;
    if (frontDoor) {
      rings.push(openingOutline(DOOR.width, DOOR.height, DOOR.rise)
        .map(([x, y]) => new THREE.Vector3(DOOR.x + x, DOOR.base + y, DOOR.z)));
    }
    const [contour, ...voids] = rings.map(ring => {
      const projected = ring.map(p => new THREE.Vector2(p.dot(u), p.dot(v)));
      if (projected[0].equals(projected.at(-1))) {
        projected.pop();
        ring.pop();
      }
      return projected;
    });
    const vertices = rings.flat();
    const tint = kind === 0 ? brick : horizontalRoof ? flatRoof : tile;
    for (const face of THREE.ShapeUtils.triangulateShape(contour, voids)) {
      const [a, b, c] = face.map(i => vertices[i]);
      const side = new THREE.Vector3().subVectors(b, a).cross(new THREE.Vector3().subVectors(c, a));
      if (side.lengthSq() < 1e-10) continue;
      for (const p of side.dot(normal) >= 0 ? [a, b, c] : [a, c, b]) {
        pos.push(p.x, p.y, p.z);
        normals.push(normal.x, normal.y, normal.z);
        color.push(tint.r, tint.g, tint.b);
        coords.push(p.dot(u) / 1.02, p.dot(v) / (kind === 0 ? 0.64 : 2.15));
        finish.push(kind === 0 ? 1 : horizontalRoof ? 0 : 2, 0.91);
      }
    }
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  geometry.setAttribute('normal', new THREE.Float32BufferAttribute(normals, 3));
  geometry.setAttribute('color', new THREE.Float32BufferAttribute(color, 3));
  geometry.setAttribute('uv', new THREE.Float32BufferAttribute(coords, 2));
  geometry.setAttribute('frisoFinish', new THREE.Float32BufferAttribute(finish, 2));
  return geometry;
}

// Window axes, sandstone bands and the recessed arched portal follow monument 523488
// and the restoration photography. Smaller surrounds and joinery are fitted to the survey.
export function createFrisoKazerne() {
  const material = facadeMaterial();
  const shell = new THREE.Mesh(surveyGeometry(), material);
  const parts = [shell.geometry];
  const ray = new THREE.Raycaster();
  const inward = new THREE.Vector3(0, 0, -1);
  function frontAt(x, y) {
    ray.ray.origin.set(x, y, 2);
    ray.ray.direction.copy(inward);
    return ray.intersectObject(shell, false)[0]?.point.z;
  }

  function detail(geometry, hex, roughness = 0.82, pattern = 0) {
    if (geometry.index) {
      const source = geometry;
      geometry = source.toNonIndexed();
      source.dispose();
    }
    const size = geometry.attributes.position.count;
    const tint = new THREE.Color(hex), fills = new Float32Array(size * 3), finishes = new Float32Array(size * 2);
    for (let i = 0; i < size; i++) {
      tint.toArray(fills, i * 3);
      finishes.set([pattern, roughness], i * 2);
    }
    geometry.setAttribute('color', new THREE.BufferAttribute(fills, 3));
    geometry.setAttribute('frisoFinish', new THREE.BufferAttribute(finishes, 2));
    parts.push(geometry);
  }

  function box(x, y, z, width, height, depth, color) {
    detail(new THREE.BoxGeometry(width, height, depth).translate(x, y, z), color);
  }

  function panel(outline, x, y, z, color, roughness) {
    const shape = new THREE.Shape(outline.map(p => new THREE.Vector2(...p)));
    detail(new THREE.ShapeGeometry(shape).translate(x, y, z), color, roughness);
  }

  function window(x, y, width, height, arch = 0, depth = frontAt(x, y + height / 2)) {
    if (depth == null || depth < -1.1) return;
    panel(openingOutline(width + 0.16, height + 0.14, arch), x, y - 0.06, depth + 0.028, FRAME);
    panel(openingOutline(width - 0.045, height - 0.09, arch), x, y + 0.04, depth + 0.04, GLASS, 0.27);
    box(x, y - 0.07, depth + 0.045, width + 0.32, 0.11, 0.35, SILL);
    box(x, y + height * 0.57, depth + 0.052, width, 0.065, 0.042, FRAME);
    box(x, y + (height - arch) * 0.48, depth + 0.052, 0.065, (height - arch) * 0.94, 0.042, FRAME);
  }

  for (const x of [-11.18, -8.18, -5.43, 2.36, 5.22, 8.15]) {
    for (const y of [0.60, 4.85, 9.03]) window(x, y, 1.42, 2.92, 0.33);
  }
  for (const x of [-2.35, -0.74]) for (const y of [4.85, 9.03]) window(x, y, 1.10, 2.92, 0.33);
  for (const [start, end] of [[-51.84, -13.79], [10.05, 48.76]]) {
    const spacing = (end - start) / 15;
    for (let i = 0; i < 15; i++) {
      const x = start + spacing * (i + 0.5);
      if (i === 3 || i === 11) {
        panel(openingOutline(1.53, 2.91, 0.28), x, 0.15, -0.158, WOOD);
        panel(openingOutline(1.45, 0.78, 0.23), x, 2.75, -0.151, GLASS, 0.27);
      } else {
        window(x, 0.53, 1.44, 2.82, 0.29);
      }
      window(x, 4.78, 1.44, 2.35);
    }
    for (const y of [0.29, 3.89, 7.86]) box((start + end) / 2, y, -0.10, end - start, 0.11, 0.28, y > 7 ? STONE : SILL);
  }
  for (const [start, end] of [[-65.59, -52.51], [49.29, 62.4]]) {
    const spacing = (end - start) / 4;
    for (let i = 0; i < 4; i++) {
      const x = start + spacing * (i + 0.5);
      window(x, 0.62, 1.52, 2.98, 0.33);
      window(x, 4.94, 1.52, 2.64, 0.35);
    }
    for (const y of [0.29, 4.06, 8.48]) box((start + end) / 2, y, 0.91, end - start, 0.12, 0.34, y > 8 ? STONE : SILL);
  }

  for (const y of [0.31, 4.05, 8.23, 12.38]) box(-1.59, y, 0.97, 22.5, 0.12, 0.34, y > 12 ? STONE : SILL);
  for (const x of [-12.60, -4.30, 1.20, 9.40]) {
    for (let y = 1.0; y < 12; y += 1.42) box(x, y, 0.93, 0.54, 0.16, 0.24, STONE);
  }
  // The small stepped gable and dormers are finer than the roof survey.
  const gable = [
    [-2.25, 0], [2.25, 0], [2.25, 1.64], [1.84, 1.64], [1.84, 2.09],
    [1.25, 2.09], [1.25, 2.77], [0.75, 2.77], [0.75, 3.78],
    [-0.75, 3.78], [-0.75, 2.77], [-1.25, 2.77], [-1.25, 2.09],
    [-1.84, 2.09], [-1.84, 1.64], [-2.25, 1.64],
  ];
  const attic = new THREE.Shape(gable.map(p => new THREE.Vector2(...p)));
  detail(new THREE.ExtrudeGeometry(attic, { depth: 0.72, bevelEnabled: false }).translate(DOOR.x, 12.52, 0.47), BRICK, 0.91, 1);
  box(DOOR.x, 16.33, 0.84, 1.65, 0.11, 0.80, SILL);
  box(DOOR.x, 12.86, 1.20, 4.45, 0.11, 0.18, SILL);
  window(DOOR.x, 13.05, 0.82, 1.64, 0.22, 1.19);
  for (const x of [DOOR.x - 0.31, DOOR.x + 0.31]) {
    panel(openingOutline(0.24, 0.48, 0.12), x, 15.58, 1.205, 0x3c322e);
  }
  for (const x of [-8.16, -5.77, 2.81, 5.2]) {
    const z = 0.49;
    const arch = [[-0.62, 0], [0.62, 0], [0.62, 1.34], [0, 2.23], [-0.62, 1.34]];
    const face = new THREE.Shape(arch.map(p => new THREE.Vector2(...p)));
    detail(new THREE.ExtrudeGeometry(face, { depth: 1.38, bevelEnabled: false }).translate(x, 12.87, z - 1.38), SILL);
    window(x, 13.02, 0.70, 1.11, 0, z + 0.02);
  }

  const [x, z, ground, width, height, rise] = [DOOR.x, DOOR.z, DOOR.base, DOOR.width, DOOR.height, DOOR.rise];
  const arch = new THREE.Shape(openingOutline(width + 0.53, height + 0.27, rise + 0.11).map(p => new THREE.Vector2(...p)));
  arch.holes.push(new THREE.Path(openingOutline(width - 0.08, height - 0.08, rise)
    .map(([u, v]) => new THREE.Vector2(u, v + 0.04))));
  detail(new THREE.ExtrudeGeometry(arch, { depth: 0.24, bevelEnabled: false }).translate(x, ground - 0.03, z - 0.04), STONE);
  panel(openingOutline(width + 0.5, height + 0.17, rise), x, 0.021, z - 0.294, 0x302720);
  panel(openingOutline(width - 0.1, height - 0.07, rise), x, ground + 0.02, z - 0.26, WOOD);
  panel(openingOutline(width - 0.21, 1.13, 0.77), x, ground + 2.25, z - 0.249, GLASS, 0.31);
  box(x, 1.58, z - 0.225, 0.09, 2.95, 0.055, WOOD);
  for (const offset of [-0.62, 0.62]) {
    box(x + offset, 1.1, z - 0.24, 0.74, 1.4, 0.035, 0x714331);
    box(x + offset, 2.03, z - 0.237, 0.68, 0.34, 0.039, 0x714331);
  }
  box(x, 3.86, z + 0.15, 3.15, 0.41, 0.30, STONE);
  box(x, 4.04, z + 0.20, 3.36, 0.11, 0.41, STONE);
  box(x, 0.06, z + 0.36, 3.52, 0.18, 0.98, SILL);
  for (const offset of [-2.11, 2.11]) {
    box(x + offset, 2.63, z + 0.11, 0.085, 0.09, 0.30, 0x252321);
    box(x + offset, 2.39, z + 0.26, 0.16, 0.33, 0.19, 0x605543);
    box(x + offset, 2.57, z + 0.27, 0.21, 0.07, 0.23, 0x252321);
  }

  const mesh = new THREE.Mesh(mergeGeometries(parts), material);
  mesh.name = 'Historische bakstenen gevels en pannendaken';
  mesh.castShadow = true;
  mesh.receiveShadow = true;
  for (const geometry of parts) geometry.dispose();
  const group = new THREE.Group();
  group.add(mesh);

  const canvas = document.createElement('canvas');
  canvas.width = 384;
  canvas.height = 56;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#c4b596';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  ctx.fillStyle = '#3d3327';
  ctx.textAlign = 'center';
  ctx.font = 'bold 22px Georgia, serif';
  ctx.fillText('JOHAN WILLEM', 192, 23);
  ctx.fillText('FRISOKAZERNE', 192, 48);
  const panelTexture = new THREE.CanvasTexture(canvas);
  panelTexture.colorSpace = THREE.SRGBColorSpace;
  const inscription = new THREE.Mesh(new THREE.PlaneGeometry(2.64, 0.36),
    new THREE.MeshStandardMaterial({ map: panelTexture, roughness: 0.87 }));
  inscription.position.set(x, 3.86, z + 0.306);
  inscription.receiveShadow = true;
  group.add(inscription);
  return group;
}
