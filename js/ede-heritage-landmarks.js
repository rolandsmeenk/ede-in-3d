let commonMaterial;
function heritageMaterial() {
  if (!commonMaterial) {
    commonMaterial = new THREE.MeshStandardNodeMaterial({ metalness: 0.02 });
    const finish = attribute('heritageFinish', 'vec2');
    const grain = texture(createFacadeSurfaceTexture().texture, uv());
    const surface = mix(grain.r, grain.b, step(1.5, finish.x));
    commonMaterial.colorNode = vertexColor().mul(mix(1, surface.mul(0.42).add(0.62), step(0.5, finish.x)));
    commonMaterial.roughnessNode = finish.y;
  }
  return commonMaterial;
}

function arch(width, height, rise) {
  const ring = [[-width / 2, 0], [width / 2, 0]];
  if (!rise) return ring.concat([[width / 2, height], [-width / 2, height]]);
  for (let i = 0; i <= 10; i++) {
    const a = Math.PI * i / 10;
    ring.push([Math.cos(a) * width / 2, height - rise + Math.sin(a) * rise]);
  }
  return ring;
}

function outsideOpening(triangle, opening, shiftX, shiftY) {
  let inside = triangle;
  const outside = [];
  for (let i = 0; i < opening.length; i++) {
    const [ax, ay] = opening[i], [bx, by] = opening[(i + 1) % opening.length];
    const inner = [], outer = [];
    const distance = p => (bx - ax) * (p.y - shiftY - ay) - (by - ay) * (p.x - shiftX - ax);
    let prev = inside.at(-1), from = distance(prev);
    for (const current of inside) {
      const to = distance(current);
      if ((from >= 0) !== (to >= 0)) {
        const crossing = prev.clone().lerp(current, from / (from - to));
        inner.push(crossing);
        outer.push(crossing);
      }
      (to >= 0 ? inner : outer).push(current);
      prev = current;
      from = to;
    }
    if (outer.length >= 3) outside.push(outer);
    if (inner.length < 3) return outside;
    inside = inner;
  }
  return outside;
}

function surveyedShell({ points, faces }, osmId, facadeColor, useBrick, door) {
  const position = [], normals = [], color = [], coords = [], finish = [];
  const local = points.map(([x, y, z]) => new THREE.Vector3(x, y === 0 ? -0.25 : y, z));
  const masonry = new THREE.Color(facadeColor);
  const pitched = new THREE.Color(TERRACOTTA);
  const flat = new THREE.Color(0x65605a);
  const rgb = [0, 0, 0];
  if (sampleRoofColor(osmId, rgb)) pitched.lerp(new THREE.Color().setRGB(...rgb), 0.28);
  const vertical = new THREE.Vector3(0, 1, 0), horizontal = new THREE.Vector3(0, 0, 1);
  const opening = door && arch(door.width, door.height, door.rise);
  for (const [kind, ...outlines] of faces) {
    const rings = outlines.map(outline => outline.map(i => local[i]));
    const boundary = rings[0], a = boundary[0];
    const normal = new THREE.Vector3();
    for (let i = 1; i < boundary.length - 1; i++) {
      normal.add(boundary[i].clone().sub(a).cross(boundary[i + 1].clone().sub(a)));
    }
    if (normal.lengthSq() < 1e-9) continue;
    normal.normalize();
    const u = new THREE.Vector3().crossVectors(Math.abs(normal.y) < 0.98 ? vertical : horizontal, normal).normalize();
    const v = new THREE.Vector3().crossVectors(normal, u);
    const [shell, ...holes] = rings.map(ring => ring.map(p => new THREE.Vector2(p.dot(u), p.dot(v))));
    const vertices = rings.flat();
    const roof = kind === 1;
    const flatRoof = roof && normal.y > 0.985;
    const tint = roof ? (flatRoof ? flat : pitched) : masonry;
    const surfaceCode = roof ? (flatRoof ? 0 : 2) : Number(useBrick);
    const cutsDoor = door && !roof && normal.z > 0.98 &&
      boundary.every(p => Math.abs(p.z - door.depth) < 0.024) &&
      boundary.some(p => p.y < door.base + door.height);
    for (const face of THREE.ShapeUtils.triangulateShape(shell, holes)) {
      const [a, b, c] = face.map(i => vertices[i]);
      const side = b.clone().sub(a).cross(c.clone().sub(a));
      if (side.lengthSq() < 1e-10) continue;
      const triangle = side.dot(normal) >= 0 ? [a, b, c] : [a, c, b];
      const polygons = cutsDoor ? outsideOpening(triangle, opening, door.x, door.base) : [triangle];
      for (const points of polygons) {
        for (let i = 1; i < points.length - 1; i++) {
          for (const p of [points[0], points[i], points[i + 1]]) {
            position.push(p.x, p.y, p.z);
            normals.push(normal.x, normal.y, normal.z);
            color.push(tint.r, tint.g, tint.b);
            coords.push(p.dot(u) / 1.05, p.dot(v) / (roof ? 2.1 : 0.64));
            finish.push(surfaceCode, 0.91);
          }
        }
      }
    }
  }
  return new THREE.BufferGeometry()
    .setAttribute('position', new THREE.Float32BufferAttribute(position, 3))
    .setAttribute('normal', new THREE.Float32BufferAttribute(normals, 3))
    .setAttribute('color', new THREE.Float32BufferAttribute(color, 3))
    .setAttribute('uv', new THREE.Float32BufferAttribute(coords, 2))
    .setAttribute('heritageFinish', new THREE.Float32BufferAttribute(finish, 2));
}

function geometryBatch(shellGeometry) {
  const parts = [shellGeometry];
  const material = heritageMaterial();
  const shell = new THREE.Mesh(shellGeometry, material);
  const ray = new THREE.Raycaster(new THREE.Vector3(), new THREE.Vector3(0, 0, -1));
  function add(geometry, hex, roughness = 0.86, pattern = 0) {
    const piece = geometry.index ? geometry.toNonIndexed() : geometry;
    if (piece !== geometry) geometry.dispose();
    const count = piece.attributes.position.count;
    const tint = new THREE.Color(hex), colors = new Float32Array(count * 3), finish = new Float32Array(count * 2);
    for (let i = 0; i < count; i++) {
      tint.toArray(colors, i * 3);
      finish.set([pattern, roughness], i * 2);
    }
    piece.setAttribute('color', new THREE.BufferAttribute(colors, 3));
    piece.setAttribute('heritageFinish', new THREE.BufferAttribute(finish, 2));
    parts.push(piece);
  }
  return {
    depth(x, y) {
      ray.ray.origin.set(x, y, 6);
      return ray.intersectObject(shell, false)[0]?.point.z;
    },
    box(x, y, z, w, h, d, hex, pattern) {
      add(new THREE.BoxGeometry(w, h, d).translate(x, y, z), hex, 0.86, pattern);
    },
    rectangle(x, y, z, width, height, hex) {
      add(new THREE.PlaneGeometry(width, height).translate(x, y, z), hex);
    },
    panel(outline, x, y, z, hex, roughness) {
      const shape = new THREE.Shape(outline.map(([a, b]) => new THREE.Vector2(a, b)));
      add(new THREE.ShapeGeometry(shape).translate(x, y, z), hex, roughness);
    },
    surround(outline, hole, x, y, z, depth, hex) {
      const shape = new THREE.Shape(outline.map(([u, v]) => new THREE.Vector2(u, v)));
      if (hole) shape.holes.push(new THREE.Path(hole.map(([u, v]) => new THREE.Vector2(u, v))));
      add(new THREE.ExtrudeGeometry(shape, { depth, bevelEnabled: false }).translate(x, y, z), hex);
    },
    mesh(name) {
      const mesh = new THREE.Mesh(mergeGeometries(parts), material);
      mesh.name = name;
      mesh.castShadow = mesh.receiveShadow = true;
      for (const geometry of parts) geometry.dispose();
      return mesh;
    },
  };
}

