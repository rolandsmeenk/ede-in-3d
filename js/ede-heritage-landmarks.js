function schoolBird(group, x, y, z) {
  if (typeof document === 'undefined') return;
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = 160;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#daddd1';
  ctx.fillRect(0, 0, 160, 160);
  ctx.fillStyle = '#a34445';
  for (const direction of [-1, 1]) {
    ctx.save();
    ctx.translate(80, 0);
    ctx.scale(direction, 1);
    for (let i = 0; i < 3; i++) {
      ctx.beginPath();
      ctx.moveTo(9, 80 - i * 8);
      ctx.quadraticCurveTo(40 + i * 6, 77 - i * 12, 69 + i * 3, 37 - i * 7);
      ctx.quadraticCurveTo(62 - i * 5, 88 - i * 12, 16, 94 - i * 8);
      ctx.fill();
    }
    ctx.restore();
  }
  ctx.beginPath();
  ctx.moveTo(51, 134);
  ctx.bezierCurveTo(76, 106, 97, 58, 77, 53);
  ctx.bezierCurveTo(86, 48, 95, 56, 94, 66);
  ctx.bezierCurveTo(94, 88, 72, 123, 74, 139);
  ctx.quadraticCurveTo(90, 147, 98, 129);
  ctx.quadraticCurveTo(103, 153, 76, 153);
  ctx.quadraticCurveTo(56, 151, 51, 134);
  ctx.fill();
  const map = new THREE.CanvasTexture(canvas);
  map.colorSpace = THREE.SRGBColorSpace;
  const emblem = new THREE.Mesh(new THREE.PlaneGeometry(0.90, 0.92),
    new THREE.MeshStandardMaterial({ map, roughness: 0.9 }));
  emblem.position.set(x, y, z);
  emblem.receiveShadow = true;
  group.add(emblem);
}

